// Uploaded media on a persistent directory (production: /opt/research-hub/data/uploads, mounted
// into the app container read-write and into Caddy read-only, which serves it at /media/).
// It is included in the nightly backup (infra/remote/backup.sh). Object storage (Tencent COS)
// can replace this later behind the same storage_key.
import { createHash, randomBytes } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { eq } from "drizzle-orm";
import type { Db } from "../db/client";
import * as s from "../db/schema";
import { inspectImage } from "./images";

export function uploadsDir(): string {
  return path.resolve(process.env.UPLOADS_DIR ?? path.join(process.cwd(), "data", "uploads"));
}

/** storage keys are generated by us; this guards every read and delete anyway */
export const KEY_RE = /^[a-z0-9]+(\/[a-z0-9_-]+)*\.(png|jpg|webp|ico)$/;

export function pathForKey(key: string): string {
  if (!KEY_RE.test(key) || key.includes("..")) throw new Error("invalid storage key");
  const full = path.resolve(uploadsDir(), key);
  if (!full.startsWith(uploadsDir() + path.sep)) throw new Error("invalid storage key");
  return full;
}

export function publicUrl(key: string): string {
  return `/media/${key}`;
}

/** Validate, store and register an uploaded image. Throws ImageError with a user-facing message. */
export async function saveImage(db: Db, input: Buffer, opts: { prefix: string; alt?: string; createdBy?: number }) {
  const img = inspectImage(input);
  const now = new Date();
  const key = `${opts.prefix}/${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, "0")}/${randomBytes(12).toString("hex")}.${img.kind}`;
  const full = pathForKey(key);
  await fs.mkdir(path.dirname(full), { recursive: true });
  await fs.writeFile(full, img.data, { flag: "wx", mode: 0o644 });
  try {
    const [row] = await db
      .insert(s.media)
      .values({
        storageKey: key,
        mime: img.mime,
        bytes: img.data.length,
        width: img.width,
        height: img.height,
        sha256: createHash("sha256").update(img.data).digest(),
        alt: opts.alt?.trim().slice(0, 200) || null,
        createdBy: opts.createdBy ?? null,
      })
      .returning();
    return row;
  } catch (err) {
    await fs.rm(full, { force: true });
    throw err;
  }
}

/** Remove a media row and its file (file errors are ignored: the row is the source of truth). */
export async function deleteMedia(db: Db, id: number) {
  const [row] = await db.delete(s.media).where(eq(s.media.id, id)).returning({ key: s.media.storageKey });
  if (row) await fs.rm(pathForKey(row.key), { force: true }).catch(() => {});
}
